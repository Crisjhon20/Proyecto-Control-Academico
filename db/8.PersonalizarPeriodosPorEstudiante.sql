-- Convierte los periodos globales en ciclos compartidos con periodos personales.
-- La migracion conserva los ciclos e inscripciones existentes.

BEGIN;

DROP TRIGGER IF EXISTS trg_preparar_cierre_periodo ON periodo_academico;
DROP TRIGGER IF EXISTS trg_archivar_historial_periodo ON periodo_academico;

ALTER TABLE periodo_academico RENAME TO ciclo_academico;

ALTER TABLE ciclo_academico
    DROP CONSTRAINT IF EXISTS ck_periodo_academico_activo,
    DROP CONSTRAINT IF EXISTS ck_periodo_academico_cierre,
    DROP CONSTRAINT IF EXISTS uq_periodo_academico_nombre;

DROP INDEX IF EXISTS uq_periodo_academico_activo;

CREATE TABLE periodo_estudiante (
    periodo_estudiante_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiante(estudiante_id),
    ciclo_academico_id INTEGER NOT NULL REFERENCES ciclo_academico(periodo_academico_id),
    nombre VARCHAR(10) NOT NULL,
    fecha_inicio DATE,
    fecha_fin DATE,
    cerrado BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_cierre TIMESTAMPTZ,
    CONSTRAINT ck_periodo_estudiante_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_periodo_estudiante_fechas CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_inicio <= fecha_fin),
    CONSTRAINT ck_periodo_estudiante_activo CHECK (activo = FALSE OR cerrado = FALSE),
    CONSTRAINT ck_periodo_estudiante_cierre CHECK ((cerrado = FALSE AND fecha_cierre IS NULL) OR (cerrado = TRUE AND fecha_cierre IS NOT NULL)),
    CONSTRAINT uq_periodo_estudiante_ciclo UNIQUE (estudiante_id, ciclo_academico_id)
);

INSERT INTO periodo_estudiante (estudiante_id, ciclo_academico_id, nombre, cerrado, activo, fecha_cierre)
SELECT estudiante.estudiante_id,
       ciclo.periodo_academico_id,
       ciclo.nombre,
       ciclo.cerrado,
       ciclo.activo,
       ciclo.fecha_cierre
  FROM estudiante
 CROSS JOIN ciclo_academico AS ciclo;

ALTER TABLE inscripcion
    ADD COLUMN periodo_estudiante_id INTEGER;

UPDATE inscripcion AS inscripcion
   SET periodo_estudiante_id = periodo_estudiante.periodo_estudiante_id
  FROM periodo_estudiante
 WHERE periodo_estudiante.estudiante_id = inscripcion.estudiante_id
   AND periodo_estudiante.ciclo_academico_id = inscripcion.periodo_academico_id;

ALTER TABLE historial_academico
    ADD COLUMN periodo_estudiante_id INTEGER;

UPDATE historial_academico AS historial
   SET periodo_estudiante_id = periodo_estudiante.periodo_estudiante_id
  FROM periodo_estudiante
 WHERE periodo_estudiante.estudiante_id = historial.estudiante_id
   AND periodo_estudiante.ciclo_academico_id = historial.periodo_academico_id;

ALTER TABLE inscripcion
    DROP CONSTRAINT IF EXISTS uq_inscripcion_estudiante_materia_periodo,
    DROP CONSTRAINT IF EXISTS inscripcion_periodo_academico_id_fkey,
    ALTER COLUMN periodo_estudiante_id SET NOT NULL,
    ADD CONSTRAINT fk_inscripcion_periodo_estudiante
        FOREIGN KEY (periodo_estudiante_id) REFERENCES periodo_estudiante(periodo_estudiante_id),
    ADD CONSTRAINT uq_inscripcion_estudiante_materia_periodo
        UNIQUE (estudiante_id, materia_id, periodo_estudiante_id);

ALTER TABLE historial_academico
    DROP CONSTRAINT IF EXISTS uq_historial_estudiante_materia_periodo,
    DROP CONSTRAINT IF EXISTS historial_academico_periodo_academico_id_fkey,
    ALTER COLUMN periodo_estudiante_id SET NOT NULL,
    ADD CONSTRAINT fk_historial_periodo_estudiante
        FOREIGN KEY (periodo_estudiante_id) REFERENCES periodo_estudiante(periodo_estudiante_id),
    ADD CONSTRAINT uq_historial_estudiante_materia_periodo
        UNIQUE (estudiante_id, materia_id, periodo_estudiante_id);

ALTER TABLE inscripcion DROP COLUMN periodo_academico_id;
ALTER TABLE historial_academico DROP COLUMN periodo_academico_id;

ALTER TABLE ciclo_academico
    DROP COLUMN cerrado,
    DROP COLUMN activo,
    DROP COLUMN fecha_cierre,
    ADD CONSTRAINT ck_ciclo_academico_nombre
        CHECK (nombre IS NOT NULL AND nombre ~ '^[0-9]{4}-(I|II)$'),
    ADD CONSTRAINT uq_ciclo_academico_nombre UNIQUE (nombre);

CREATE UNIQUE INDEX uq_periodo_estudiante_activo
    ON periodo_estudiante (estudiante_id)
    WHERE activo = TRUE;

CREATE INDEX idx_periodo_estudiante_ciclo
    ON periodo_estudiante (ciclo_academico_id);

CREATE OR REPLACE FUNCTION preparar_cierre_periodo_estudiante()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.cerrado = TRUE AND OLD.cerrado = FALSE THEN
        NEW.fecha_cierre := COALESCE(NEW.fecha_cierre, CURRENT_TIMESTAMP);
        NEW.activo := FALSE;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION archivar_historial_periodo_estudiante()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.cerrado = TRUE AND OLD.cerrado = FALSE THEN
        INSERT INTO historial_academico
            (estudiante_id, materia_id, periodo_estudiante_id,
             semestre_cursado, nota_final, estado)
         SELECT i.estudiante_id,
                i.materia_id,
                i.periodo_estudiante_id,
                i.semestre_cursado,
                ROUND(COALESCE(SUM(n.nota * e.porcentaje / 100), 0), 2),
                CASE
                    WHEN i.estado = 'Retirada' THEN 'Retirada'
                    WHEN COALESCE(SUM(n.nota * e.porcentaje / 100), 0) >= 51 THEN 'Aprobada'
                    ELSE 'Reprobada'
                END
           FROM inscripcion i
           LEFT JOIN evaluacion e ON e.inscripcion_id = i.inscripcion_id
           LEFT JOIN nota n ON n.evaluacion_id = e.evaluacion_id
          WHERE i.periodo_estudiante_id = NEW.periodo_estudiante_id
          GROUP BY i.estudiante_id, i.materia_id,
                   i.periodo_estudiante_id, i.semestre_cursado, i.estado
        ON CONFLICT (estudiante_id, materia_id, periodo_estudiante_id)
        DO NOTHING;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_preparar_cierre_periodo_estudiante
BEFORE UPDATE OF cerrado ON periodo_estudiante
FOR EACH ROW EXECUTE FUNCTION preparar_cierre_periodo_estudiante();

CREATE TRIGGER trg_archivar_historial_periodo_estudiante
AFTER UPDATE OF cerrado ON periodo_estudiante
FOR EACH ROW EXECUTE FUNCTION archivar_historial_periodo_estudiante();

DROP FUNCTION IF EXISTS preparar_cierre_periodo();
DROP FUNCTION IF EXISTS archivar_historial_periodo();

COMMIT;
