-- Ejecutar este archivo conectado a la base de datos controlacademico.

CREATE TABLE estudiante (
    estudiante_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_registro VARCHAR(20),
    nombres VARCHAR(100),
    apellidos VARCHAR(100),
    numero_celular VARCHAR(20),
    contrasena VARCHAR(255),
    rol VARCHAR(20) DEFAULT 'ESTUDIANTE'
);

CREATE TABLE malla_curricular (
    malla_curricular_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150)
);

CREATE TABLE materia (
    materia_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10),
    nombre VARCHAR(120),
    semestre SMALLINT,
    creditos SMALLINT DEFAULT 5,
    malla_curricular_id INTEGER REFERENCES malla_curricular(malla_curricular_id)
);

CREATE TABLE periodo_academico (
    periodo_academico_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(10)
);

CREATE TABLE docente (
    docente_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100),
    apellidos VARCHAR(100)
);

CREATE TABLE aula (
    aula_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero SMALLINT
);

CREATE TABLE asignacion_materia (
    asignacion_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id INTEGER REFERENCES materia(materia_id),
    periodo_academico_id INTEGER REFERENCES periodo_academico(periodo_academico_id),
    docente_id INTEGER REFERENCES docente(docente_id),
    aula_id INTEGER REFERENCES aula(aula_id)
);

CREATE TABLE inscripcion (
    inscripcion_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER REFERENCES estudiante(estudiante_id),
    materia_id INTEGER REFERENCES materia(materia_id),
    periodo_academico_id INTEGER REFERENCES periodo_academico(periodo_academico_id),
    semestre_cursado SMALLINT,
    estado VARCHAR(10)
);

CREATE TABLE evaluacion (
    evaluacion_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id INTEGER REFERENCES materia(materia_id),
    nombre VARCHAR(80),
    porcentaje NUMERIC(5, 2)
);

CREATE TABLE nota (
    nota_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscripcion_id INTEGER REFERENCES inscripcion(inscripcion_id),
    evaluacion_id INTEGER REFERENCES evaluacion(evaluacion_id),
    nota NUMERIC(5, 2)
);

CREATE TABLE horario (
    horario_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscripcion_id INTEGER REFERENCES inscripcion(inscripcion_id),
    dia_semana VARCHAR(15),
    hora_inicio TIME,
    hora_fin TIME
);

CREATE TABLE asistencia (
    asistencia_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscripcion_id INTEGER REFERENCES inscripcion(inscripcion_id),
    fecha_clase DATE,
    estado VARCHAR(10)
);
